OVERLAY_ALPHA = 0.45
OVERLAY_COLOR = np.array([255, 0, 0], dtype=np.uint8)  # Đỏ


def create_overlay(image_pil: Image.Image, mask_np: np.ndarray, alpha: float = OVERLAY_ALPHA) -> Image.Image:
    """
    Tạo ảnh overlay: ảnh gốc + mask đỏ bán trong suốt tại vùng giả mạo.
    mask_np: (H, W) binary 0/1
    """
    img_arr = np.array(image_pil).copy()
    h_img, w_img = img_arr.shape[:2]
    h_mask, w_mask = mask_np.shape

    if (h_img, w_img) != (h_mask, w_mask):
        mask_pil = Image.fromarray((mask_np * 255).astype(np.uint8))
        mask_pil = mask_pil.resize((w_img, h_img), Image.NEAREST)
        mask_resized = np.array(mask_pil) > 127
    else:
        mask_resized = mask_np.astype(bool)

    overlay = img_arr.copy()
    overlay[mask_resized] = (
        (1 - alpha) * img_arr[mask_resized].astype(np.float32)
        + alpha * OVERLAY_COLOR.astype(np.float32)
    ).astype(np.uint8)

    return Image.fromarray(overlay)


