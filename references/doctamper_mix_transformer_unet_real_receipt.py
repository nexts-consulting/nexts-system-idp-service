IMG_NORMALIZE = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
])

IMAGENET_MEAN = torch.tensor([0.485, 0.456, 0.406], device=DEVICE).view(1, 3, 1, 1)
IMAGENET_STD  = torch.tensor([0.229, 0.224, 0.225], device=DEVICE).view(1, 3, 1, 1)

IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".bmp", ".tiff"}


def collect_image_paths(folder: Path) -> list:
    """Thu thập tất cả file ảnh trong folder, sắp xếp theo tên."""
    if not folder.is_dir():
        print(f"WARNING: Folder không tồn tại: {folder}")
        return []
    paths = []
    for f in sorted(folder.iterdir()):
        if f.suffix.lower() in IMAGE_EXTENSIONS and f.is_file():
            paths.append(f)
    return paths


@torch.no_grad()
def infer_single_image(image_path: Path) -> dict:
    """
    Chạy inference trên 1 ảnh, giữ nguyên kích thước gốc.
    Returns dict với: image_pil, mask_np (H,W binary 0/1),
                      prob_map (H,W float), tamper_ratio, predicted_label
    """
    image_pil = Image.open(image_path).convert("RGB")
    w_orig, h_orig = image_pil.size

    x = IMG_NORMALIZE(image_pil).unsqueeze(0).to(DEVICE, non_blocking=True)

    with torch.amp.autocast("cuda", dtype=amp_dtype, enabled=use_amp):
        logits = model(x)  # [1, 2, H, W]

    prob_fg = torch.softmax(logits, dim=1)[0, 1].cpu().numpy()   # P(tampered)
    mask_binary = (logits.argmax(dim=1)[0]).cpu().numpy().astype(np.uint8)  # 0 or 1

    tamper_pixels = mask_binary.sum()
    total_pixels = mask_binary.shape[0] * mask_binary.shape[1]
    tamper_ratio = tamper_pixels / total_pixels

    predicted_tampered = tamper_ratio >= TAMPER_PIXEL_THRESHOLD

    return {
        "image_path": image_path,
        "image_pil": image_pil,
        "w_orig": w_orig,
        "h_orig": h_orig,
        "mask_np": mask_binary,
        "prob_map": prob_fg,
        "tamper_ratio": tamper_ratio,
        "tamper_pixels": int(tamper_pixels),
        "total_pixels": int(total_pixels),
        "predicted_tampered": predicted_tampered,
    }


def run_inference_on_folder(folder: Path, ground_truth_label: int, label_name: str) -> list:
    """
    Chạy inference trên tất cả ảnh trong folder.
    ground_truth_label: 0 = normal, 1 = tampered
    Returns list of result dicts.
    """
    paths = collect_image_paths(folder)
    print(f"\n{'='*60}")
    print(f"Folder: {folder.name} ({label_name}) — {len(paths)} ảnh")
    print(f"Ground truth label: {ground_truth_label} ({'tampered' if ground_truth_label == 1 else 'normal'})")
    print(f"{'='*60}")

    results = []
    for p in tqdm(paths, desc=f"Inference [{label_name}]"):
        res = infer_single_image(p)
        res["ground_truth"] = ground_truth_label
        res["ground_truth_label"] = label_name
        results.append(res)

    correct = sum(1 for r in results if r["predicted_tampered"] == bool(ground_truth_label))
    print(f"Accuracy trên folder {label_name}: {correct}/{len(results)} ({100*correct/max(len(results),1):.1f}%)")
    return results


