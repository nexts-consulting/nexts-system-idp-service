def display_results(results: list, max_per_row: int = 4):
    """Hiển thị ảnh gốc + mask dự đoán, chia thành các hàng."""
    n = len(results)
    if n == 0:
        print("Không có kết quả để hiển thị.")
        return

    n_rows = (n + max_per_row - 1) // max_per_row

    for row_idx in range(n_rows):
        start = row_idx * max_per_row
        end = min(start + max_per_row, n)
        batch = results[start:end]
        cols = len(batch)

        fig, axes = plt.subplots(2, cols, figsize=(5 * cols, 8))
        if cols == 1:
            axes = np.array(axes).reshape(2, 1)

        for i, res in enumerate(batch):
            gt = "NORMAL" if res["ground_truth"] == 0 else "TAMPERED"
            pred = "TAMPERED" if res["predicted_tampered"] else "NORMAL"
            correct = "✓" if (res["predicted_tampered"] == bool(res["ground_truth"])) else "✗"
            ratio_pct = res["tamper_ratio"] * 100

            axes[0, i].imshow(res["image_pil"])
            axes[0, i].set_title(
                f"{res['image_path'].name}\nGT: {gt} | Pred: {pred} {correct}\n"
                f"Tamper: {ratio_pct:.2f}%",
                fontsize=8,
            )
            axes[0, i].axis("off")

            axes[1, i].imshow(res["mask_np"], vmin=0, vmax=1, cmap="Reds")
            axes[1, i].set_title("Mask dự đoán (vùng chỉnh sửa)", fontsize=8)
            axes[1, i].axis("off")

        plt.tight_layout()
        plt.show()


