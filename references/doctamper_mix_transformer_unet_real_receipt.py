import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
from pathlib import Path
from sklearn.metrics import ConfusionMatrixDisplay

def evaluate_from_counts(tn, fp, fn, tp, output_dir="outputs"):
    """
    Evaluates model performance using raw TP, FP, FN, TN counts.
    """
    OUT_DIR = Path(output_dir)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Manually construct the Confusion Matrix array
    # Format: [[TN, FP], [FN, TP]]
    cm = np.array([[tn, fp], [fn, tp]])

    # 2. Calculate Metrics from formulas
    # We use LaTeX-style logic for clarity:
    # Accuracy = (TP + TN) / Total
    total = tn + fp + fn + tp
    acc  = (tp + tn) / total if total > 0 else 0
    prec = tp / (tp + fp) if (tp + fp) > 0 else 0
    rec  = tp / (tp + fn) if (tp + fn) > 0 else 0
    f1   = 2 * (prec * rec) / (prec + rec) if (prec + rec) > 0 else 0

    # 3. Visualization
    fig, ax = plt.subplots(figsize=(6, 5))
    disp = ConfusionMatrixDisplay(
        confusion_matrix=cm,
        display_labels=["Normal (0)", "Tampered (1)"],
    )
    disp.plot(ax=ax, cmap="Blues", values_format="d")
    ax.set_title("Confusion Matrix (Manual Input)", fontsize=14)

    cm_path = OUT_DIR / "manual_confusion_matrix.png"
    plt.tight_layout()
    fig.savefig(cm_path, dpi=150)
    plt.show()

    # 4. Summary Table
    metrics_summary = pd.DataFrame([{
        "True Negatives": tn,
        "False Positives": fp,
        "False Negatives": fn,
        "True Positives": tp,
        "Accuracy": round(acc, 4),
        "Precision": round(prec, 4),
        "Recall": round(rec, 4),
        "F1-Score": round(f1, 4),
    }])

    return metrics_summary

